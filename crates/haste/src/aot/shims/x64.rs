fn emit_x64_tls_get(c: &Emit<'_>, key_va: u64, out: &mut Buf) -> Result<()> {
    out.bytes(&[0x4C, 0x8D, 0x2D]);
    out.u32(((key_va as i64 - (c.at(out) as i64 + 4)) as i32) as u32);
    let ready_fast = x64_jcc(&[0x41, 0x8B, 0x45, 0x00, 0x83, 0xF8, 0x02], 0x74, out);
    let init_loop = out.pos();
    let do_create = x64_jcc(
        &[
            0x31, 0xC0, 0xBA, 1, 0, 0, 0, 0xF0, 0x41, 0x0F, 0xB1, 0x55, 0x00,
        ],
        0x74,
        out,
    );
    let ready_wait = x64_jcc(&[0x83, 0xF8, 0x02], 0x74, out);
    c.call(c.pick("SwitchToThread", "sched_yield"), out)?;
    out.bytes(&[
        0xEB,
        ((init_loop as isize - (out.pos() as isize + 2)) as i8) as u8,
    ]);
    x64_patch8(do_create, out);
    if c.win {
        c.call("TlsAlloc", out)?;
        out.bytes(&[0x41, 0x89, 0x45, 0x08]);
    } else {
        c.bytes_call(
            &[0x49, 0x8D, 0x7D, 0x08, 0x31, 0xF6],
            "pthread_key_create",
            out,
        )?;
    }
    out.bytes(&[0x41, 0xC7, 0x45, 0x00, 0x02, 0, 0, 0]);
    x64_here(&[ready_fast, ready_wait], out);
    let reg = if c.win {
        &[0x41, 0x8B, 0x4D, 0x08][..]
    } else {
        &[0x49, 0x8B, 0x7D, 0x08]
    };
    c.bytes_call(reg, c.pick("TlsGetValue", "pthread_getspecific"), out)
}

pub(in crate::aot) fn emit_x64_unwind_state(
    c: &Emit<'_>,
    addrs: SectionAddrs,
    out: &mut Buf,
) -> Result<()> {
    if addrs.unwind_tls != 0 {
        tls::emit_x64_tls_unwind_state(addrs.unwind_tls, out);
        return Ok(());
    }
    emit_x64_tls_get(c, addrs.thread_key + 16, out)?;
    let hit = x64_jcc(&[0x48, 0x85, 0xC0], 0x75, out);
    const _: () = assert!(tls::UNWIND_STATE_BYTES <= 0xFF);
    let size = tls::UNWIND_STATE_BYTES as u8;
    let calloc_args = if c.win {
        [0xB9, 1, 0, 0, 0, 0xBA, size, 0, 0, 0]
    } else {
        [0xBF, 1, 0, 0, 0, 0xBE, size, 0, 0, 0]
    };
    c.bytes_call(&calloc_args, "calloc", out)?;
    let fail = x64_jcc(&[0x48, 0x85, 0xC0], 0x74, out);
    let set_args = if c.win {
        &[0x48, 0x89, 0xC3, 0x41, 0x8B, 0x4D, 0x08, 0x48, 0x89, 0xDA][..]
    } else {
        &[0x48, 0x89, 0xC3, 0x49, 0x8B, 0x7D, 0x08, 0x48, 0x89, 0xDE]
    };
    c.bytes_call(set_args, c.pick("TlsSetValue", "pthread_setspecific"), out)?;
    out.bytes(&[0x48, 0x89, 0xD8]);
    x64_here(&[hit, fail], out);
    Ok(())
}

fn emit_x64_unlink_r12(out: &mut Buf) {
    let no_prev = x64_jcc(
        &[
            0x49, 0x8B, 0x4C, 0x24, 0x08, 0x49, 0x8B, 0x54, 0x24, 0x10, 0x48, 0x85, 0xC9,
        ],
        0x74,
        out,
    );
    out.bytes(&[0x48, 0x89, 0x51, 0x10]);
    x64_patch8(no_prev, out);
    let is_tail = x64_jcc(&[0x48, 0x85, 0xD2], 0x74, out);
    let after_next = x64_jcc(&[0x48, 0x89, 0x4A, 0x08], 0xEB, out);
    x64_patch8(is_tail, out);
    out.bytes(&[0x48, 0x89, 0x4B, 0x08]);
    x64_patch8(after_next, out);
    out.bytes(&[
        0x49, 0xC7, 0x44, 0x24, 0x08, 0, 0, 0, 0, 0x49, 0xC7, 0x44, 0x24, 0x10, 0, 0, 0, 0, 0x41,
        0x80, 0x24, 0x24, 0xFD,
    ]);
}

fn emit_x64_drop_op(c: &Emit<'_>, push: bool, addrs: SectionAddrs, out: &mut Buf) -> Result<()> {
    out.bytes(if c.win {
        &[0x48, 0x85, 0xC9, 0x75, 0x01, 0xC3]
    } else {
        &[0x48, 0x85, 0xFF, 0x75, 0x01, 0xC3]
    });
    if !push {
        out.bytes(if c.win {
            &[0xF6, 0x01, 0x02, 0x75, 0x01, 0xC3]
        } else {
            &[0xF6, 0x07, 0x02, 0x75, 0x01, 0xC3]
        });
    }
    out.bytes(if c.win {
        &[
            0x53, 0x41, 0x54, 0x41, 0x55, 0x48, 0x83, 0xEC, 0x20, 0x49, 0x89, 0xCC,
        ]
    } else {
        &[0x53, 0x41, 0x54, 0x41, 0x55, 0x49, 0x89, 0xFC]
    });
    emit_x64_unwind_state(c, addrs, out)?;
    let no_state = x64_jcc(&[0x48, 0x85, 0xC0], 0x74, out);
    out.bytes(&[0x48, 0x89, 0xC3]);
    if push {
        let not_linked = x64_jcc(&[0x41, 0xF6, 0x04, 0x24, 0x02], 0x74, out);
        emit_x64_unlink_r12(out);
        x64_patch8(not_linked, out);
        let no_head = x64_jcc(
            &[
                0x48, 0x8B, 0x4B, 0x08, 0x49, 0x89, 0x4C, 0x24, 0x08, 0x49, 0xC7, 0x44, 0x24, 0x10,
                0, 0, 0, 0, 0x41, 0x80, 0x0C, 0x24, 0x02, 0x48, 0x85, 0xC9,
            ],
            0x74,
            out,
        );
        out.bytes(&[0x4C, 0x89, 0x61, 0x10]);
        x64_patch8(no_head, out);
        out.bytes(&[0x4C, 0x89, 0x63, 0x08]);
    } else {
        emit_x64_unlink_r12(out);
    }
    x64_patch8(no_state, out);
    if c.win {
        out.bytes(&[0x48, 0x83, 0xC4, 0x20]);
    }
    out.bytes(&[0x41, 0x5D, 0x41, 0x5C, 0x5B, 0xC3]);
    Ok(())
}

fn emit_x64_thread_cell(c: &Emit<'_>, key_va: u64, out: &mut Buf) -> Result<()> {
    out.bytes(&[
        0x53,
        0x41,
        0x54,
        0x41,
        0x55,
        0x41,
        0x56,
        0x41,
        0x57,
        0x48,
        0x83,
        0xEC,
        if c.win { 0x30 } else { 0x10 },
    ]);
    out.bytes(if c.win {
        &[
            0x4C, 0x89, 0x44, 0x24, 0x20, 0x48, 0x89, 0xCB, 0xB8, 1, 0, 0, 0, 0x48, 0x85, 0xD2,
            0x48, 0x0F, 0x44, 0xD0, 0x49, 0x89, 0xD4,
        ]
    } else {
        &[
            0x48, 0x89, 0x54, 0x24, 0x08, 0x48, 0x89, 0xFB, 0xB8, 1, 0, 0, 0, 0x48, 0x85, 0xF6,
            0x48, 0x0F, 0x44, 0xF0, 0x49, 0x89, 0xF4,
        ]
    });
    emit_x64_tls_get(c, key_va, out)?;
    let grow_null = x64_jcc(&[0x49, 0x89, 0xC6, 0x4D, 0x85, 0xF6], 0x74, out);
    let grow_cap = x64_jcc(&[0x49, 0x3B, 0x1E], 0x73, out);
    out.bytes(&[0x49, 0x8B, 0x44, 0xDE, 0x08, 0x48, 0x85, 0xC0]);
    let hit = x64_fwd32(&[0x0F, 0x85], out);
    let cell_skip = x64_fwd32(&[0xE9], out);
    x64_here(&[grow_null, grow_cap], out);
    out.bytes(&[
        0x31, 0xC0, 0x4D, 0x85, 0xF6, 0x74, 0x03, 0x49, 0x8B, 0x06, 0x48, 0x01, 0xC0, 0x4C, 0x8D,
        0x7B, 0x08, 0x4C, 0x39, 0xF8, 0x4C, 0x0F, 0x47, 0xF8,
    ]);
    let calloc_args = if c.win {
        &[0x49, 0x8D, 0x4F, 1, 0xBA, 8, 0, 0, 0][..]
    } else {
        &[0x49, 0x8D, 0x7F, 1, 0xBE, 8, 0, 0, 0]
    };
    c.bytes_call(calloc_args, "calloc", out)?;
    let fail_calloc = x64_jcc(&[0x48, 0x85, 0xC0], 0x74, out);
    let no_copy = x64_jcc(
        &[0x4C, 0x89, 0x38, 0x49, 0x89, 0xC7, 0x4D, 0x85, 0xF6],
        0x74,
        out,
    );
    let memcpy_args = if c.win {
        &[
            0x49, 0x8D, 0x4F, 8, 0x49, 0x8D, 0x56, 8, 0x4D, 0x8B, 0x06, 0x49, 0xC1, 0xE0, 3,
        ][..]
    } else {
        &[
            0x49, 0x8D, 0x7F, 8, 0x49, 0x8D, 0x76, 8, 0x49, 0x8B, 0x16, 0x48, 0xC1, 0xE2, 3,
        ]
    };
    c.bytes_call(memcpy_args, "memcpy", out)?;
    c.bytes_call(
        if c.win {
            &[0x4C, 0x89, 0xF1]
        } else {
            &[0x4C, 0x89, 0xF7]
        },
        "free",
        out,
    )?;
    x64_patch8(no_copy, out);
    let set_args = if c.win {
        &[0x4D, 0x89, 0xFE, 0x41, 0x8B, 0x4D, 8, 0x4C, 0x89, 0xF2][..]
    } else {
        &[0x4D, 0x89, 0xFE, 0x49, 0x8B, 0x7D, 8, 0x4C, 0x89, 0xF6]
    };
    c.bytes_call(set_args, c.pick("TlsSetValue", "pthread_setspecific"), out)?;
    let fail_set = x64_jcc(&[0x85, 0xC0], if c.win { 0x74 } else { 0x75 }, out);
    x64_patch32(cell_skip, out);
    let fail_align = if c.win {
        c.bytes_call(
            &[0x4C, 0x89, 0xE1, 0xBA, 0x40, 0, 0, 0],
            "_aligned_malloc",
            out,
        )?;
        let f = x64_jcc(&[0x48, 0x85, 0xC0], 0x74, out);
        c.bytes_call(
            &[0x48, 0x89, 0xC1, 0x31, 0xD2, 0x4D, 0x89, 0xE0],
            "memset",
            out,
        )?;
        f
    } else {
        c.bytes_call(
            &[
                0x48, 0xC7, 0x04, 0x24, 0, 0, 0, 0, 0x48, 0x89, 0xE7, 0xBE, 0x40, 0, 0, 0, 0x4C,
                0x89, 0xE2,
            ],
            "posix_memalign",
            out,
        )?;
        let f = x64_jcc(&[0x85, 0xC0], 0x75, out);
        c.bytes_call(
            &[0x48, 0x8B, 0x3C, 0x24, 0x31, 0xF6, 0x4C, 0x89, 0xE2],
            "memset",
            out,
        )?;
        f
    };
    let init_off = if c.win { 0x20 } else { 0x08 };
    out.bytes(&[
        0x49, 0x89, 0x44, 0xDE, 0x08, 0x48, 0x8B, 0x4C, 0x24, init_off,
    ]);
    let skip_init = x64_jcc(&[0x48, 0x85, 0xC9], 0x74, out);
    out.bytes(&[
        0x48, 0x89, 0x44, 0x24, init_off, 0x48, 0x8B, 0x01, 0xFF, 0xD0, 0x48, 0x8B, 0x44, 0x24,
        init_off,
    ]);
    x64_patch8(skip_init, out);
    let done_ok = x64_fwd(0xEB, out);
    x64_here(&[fail_calloc, fail_set, fail_align], out);
    out.bytes(&[0x31, 0xC0]);
    x64_patch32(hit, out);
    x64_patch8(done_ok, out);
    out.bytes(&[
        0x48,
        0x83,
        0xC4,
        if c.win { 0x30 } else { 0x10 },
        0x41,
        0x5F,
        0x41,
        0x5E,
        0x41,
        0x5D,
        0x41,
        0x5C,
        0x5B,
        0xC3,
    ]);
    Ok(())
}

fn emit_x64_tls_cell(c: &Emit<'_>, tls: u64, out: &mut Buf) -> Result<()> {
    let disp = (tls as i64).wrapping_neg() as i32 as u32;
    out.bytes(&[
        0x64, 0x48, 0x8B, 0x04, 0x25, 0, 0, 0, 0, 0x48, 0x8B, 0x8C, 0xF8,
    ]);
    out.u32(disp);
    let slow = x64_jcc(&[0x48, 0x85, 0xC9], 0x74, out);
    out.bytes(&[0x48, 0x89, 0xC8, 0xC3]);
    x64_patch8(slow, out);
    out.bytes(&[
        0x53, 0x41, 0x54, 0x41, 0x55, 0x48, 0x83, 0xEC, 0x10, 0x48, 0x8D, 0x9C, 0xF8,
    ]);
    out.u32(disp);
    c.bytes_call(
        &[
            0x49, 0x89, 0xF4, 0x49, 0x89, 0xD5, 0x48, 0xC7, 0x04, 0x24, 0, 0, 0, 0, 0x48, 0x89,
            0xE7, 0xBE, 0x40, 0, 0, 0, 0x4C, 0x89, 0xE2,
        ],
        "posix_memalign",
        out,
    )?;
    let fail = x64_jcc(&[0x85, 0xC0], 0x75, out);
    c.bytes_call(
        &[0x48, 0x8B, 0x3C, 0x24, 0x31, 0xF6, 0x4C, 0x89, 0xE2],
        "memset",
        out,
    )?;
    out.bytes(&[0x48, 0x89, 0x03]);
    let skip_init = x64_jcc(&[0x4D, 0x85, 0xED], 0x74, out);
    out.bytes(&[0x49, 0x8B, 0x45, 0x00, 0xFF, 0xD0, 0x48, 0x8B, 0x03]);
    x64_patch8(skip_init, out);
    let done = x64_fwd(0xEB, out);
    x64_patch8(fail, out);
    out.bytes(&[0x31, 0xC0]);
    x64_patch8(done, out);
    out.bytes(&[0x48, 0x83, 0xC4, 0x10, 0x41, 0x5D, 0x41, 0x5C, 0x5B, 0xC3]);
    Ok(())
}

fn emit_x64_frame_cache(c: &Emit<'_>, alloc: bool, tls: u64, out: &mut Buf) -> Result<()> {
    let disp = (tls as i64).wrapping_neg() as i32 as u32;
    let (size_reg, sib) = if alloc { (0xFF, 0x3A) } else { (0xFE, 0x32) };
    out.bytes(&[0x48, 0x81, size_reg]);
    out.u32(haste_codegen::FRAME_CACHE_LIMIT);
    let big = x64_fwd(0x73, out);
    out.bytes(&[
        0x64, 0x48, 0x8B, 0x14, 0x25, 0, 0, 0, 0, 0x48, 0x8D, 0x94, sib,
    ]);
    out.u32(disp);
    let miss = if alloc {
        let m = x64_jcc(&[0x48, 0x8B, 0x02, 0x48, 0x85, 0xC0], 0x74, out);
        out.bytes(&[
            0x48, 0x8B, 0x08, 0x48, 0x89, 0x0A, 0x48, 0xFF, 0x4A, 0x08, 0xC3,
        ]);
        m
    } else {
        let full = x64_jcc(
            &[0x48, 0x83, 0x7A, 0x08, haste_codegen::FRAME_CACHE_DEPTH],
            0x73,
            out,
        );
        out.bytes(&[
            0x48, 0x8B, 0x0A, 0x48, 0x89, 0x0F, 0x48, 0x89, 0x3A, 0x48, 0xFF, 0x42, 0x08, 0xC3,
        ]);
        full
    };
    x64_here(&[big, miss], out);
    c.tail(if alloc { "malloc" } else { "free" }, out)
}

fn emit_x64_cpuid(c: &Emit<'_>, out: &mut Buf) {
    out.bytes(if c.win {
        &[
            0x53, 0x41, 0x89, 0xD1, 0x89, 0xD0, 0x45, 0x89, 0xC2, 0x49, 0x89, 0xC8, 0x44, 0x89,
            0xD1, 0x0F, 0xA2,
        ]
    } else {
        &[
            0x53, 0x49, 0x89, 0xF8, 0x41, 0x89, 0xF1, 0x41, 0x89, 0xD2, 0x89, 0xF0, 0x89, 0xD1,
            0x0F, 0xA2,
        ]
    });
    for (prefix, mask) in [
        (
            &[0x41, 0x83, 0xF9, 0x01, 0x75, 0x06, 0x81, 0xE1][..],
            !HIDDEN.leaf1_ecx,
        ),
        (
            &[
                0x41, 0x83, 0xF9, 0x07, 0x75, 0x2A, 0x45, 0x85, 0xD2, 0x75, 0x14, 0x81, 0xE3,
            ],
            !HIDDEN.leaf7_ebx,
        ),
        (&[0x81, 0xE1], !HIDDEN.leaf7_ecx),
        (&[0x81, 0xE2], !HIDDEN.leaf7_edx),
        (
            &[0xEB, 0x11, 0x41, 0x83, 0xFA, 0x01, 0x75, 0x0B, 0x25],
            !HIDDEN.leaf7_1_eax,
        ),
        (&[0x81, 0xE2], !HIDDEN.leaf7_1_edx),
        (
            &[
                0x41, 0x81, 0xF9, 0x01, 0x00, 0x00, 0x80, 0x75, 0x06, 0x81, 0xE1,
            ],
            !HIDDEN.extended_ecx,
        ),
    ] {
        out.bytes(prefix);
        out.u32(mask);
    }
    out.bytes(&[
        0x41, 0x89, 0x00, 0x41, 0x89, 0x58, 0x04, 0x41, 0x89, 0x48, 0x08, 0x41, 0x89, 0x50, 0x0C,
        0x5B, 0xC3,
    ]);
}

const ALLOC_CACHE_MAX_M1: u32 = haste_codegen::FRAME_CACHE_LIMIT - 17;

fn emit_x64_dealloc(c: &Emit<'_>, tls: u64, out: &mut Buf) -> Result<()> {
    if c.win || tls == 0 {
        return c.tail(c.pick("_aligned_free", "free"), out);
    }
    let disp = (tls as i64).wrapping_neg() as i32 as u32;
    let over_align = x64_jcc(&[0x48, 0x83, 0xFA, 0x10], 0x77, out);
    out.bytes(&[0x48, 0x8D, 0x4E, 0xFF, 0x48, 0x81, 0xF9]);
    out.u32(ALLOC_CACHE_MAX_M1);
    let big = x64_fwd(0x77, out);
    out.bytes(&[
        0x48, 0x8D, 0x76, 0x0F, 0x48, 0x83, 0xE6, 0xF0, 0x64, 0x48, 0x8B, 0x14, 0x25, 0, 0, 0, 0,
        0x48, 0x8D, 0x94, 0x32,
    ]);
    out.u32(disp);
    let full = x64_jcc(
        &[0x48, 0x83, 0x7A, 0x08, haste_codegen::FRAME_CACHE_DEPTH],
        0x73,
        out,
    );
    out.bytes(&[
        0x48, 0x8B, 0x0A, 0x48, 0x89, 0x0F, 0x48, 0x89, 0x3A, 0x48, 0xFF, 0x42, 0x08, 0xC3,
    ]);
    x64_here(&[over_align, big, full], out);
    c.tail("free", out)
}

fn emit_x64_alloc(c: &Emit<'_>, tls: u64, out: &mut Buf) -> Result<()> {
    if c.win {
        return c.bytes_tail(
            &[
                0xB8, 1, 0, 0, 0, 0x48, 0x85, 0xC9, 0x48, 0x0F, 0x44, 0xC8, 0x48, 0x85, 0xD2, 0x48,
                0x0F, 0x44, 0xD0,
            ],
            "_aligned_malloc",
            out,
        );
    }
    if tls != 0 {
        let disp = (tls as i64).wrapping_neg() as i32 as u32;
        let over_align = x64_jcc(&[0x48, 0x83, 0xFE, 0x10], 0x77, out);
        out.bytes(&[0x48, 0x8D, 0x4F, 0xFF, 0x48, 0x81, 0xF9]);
        out.u32(ALLOC_CACHE_MAX_M1);
        let big = x64_fwd(0x77, out);
        out.bytes(&[
            0x48, 0x8D, 0x7F, 0x0F, 0x48, 0x83, 0xE7, 0xF0, 0x64, 0x48, 0x8B, 0x14, 0x25, 0, 0, 0,
            0, 0x48, 0x8D, 0x94, 0x3A,
        ]);
        out.u32(disp);
        let miss = x64_jcc(&[0x48, 0x8B, 0x02, 0x48, 0x85, 0xC0], 0x74, out);
        out.bytes(&[
            0x48, 0x8B, 0x08, 0x48, 0x89, 0x0A, 0x48, 0xFF, 0x4A, 0x08, 0xC3,
        ]);
        x64_patch8(big, out);
        out.bytes(&[0xB8, 1, 0, 0, 0, 0x48, 0x85, 0xFF, 0x48, 0x0F, 0x44, 0xF8]);
        x64_patch8(miss, out);
        c.tail("malloc", out)?;
        x64_patch8(over_align, out);
        out.bytes(&[0xB8, 1, 0, 0, 0, 0x48, 0x85, 0xFF, 0x48, 0x0F, 0x44, 0xF8]);
    } else {
        c.bytes_tail(
            &[
                0xB8, 1, 0, 0, 0, 0x48, 0x85, 0xFF, 0x48, 0x0F, 0x44, 0xF8, 0x48, 0x83, 0xFE, 0x10,
                0x77, 0x05,
            ],
            "malloc",
            out,
        )?;
    }
    c.bytes_call(
        &[
            0x48, 0x83, 0xEC, 0x18, 0x48, 0xC7, 0x04, 0x24, 0, 0, 0, 0, 0x48, 0x89, 0xFA, 0x48,
            0x8D, 0x3C, 0x24,
        ],
        "posix_memalign",
        out,
    )?;
    out.bytes(&[
        0x85, 0xC0, 0x48, 0x8B, 0x04, 0x24, 0x31, 0xD2, 0x48, 0x0F, 0x45, 0xC2, 0x48, 0x83, 0xC4,
        0x18, 0xC3,
    ]);
    Ok(())
}

fn emit_x64_alloc_zeroed(c: &Emit<'_>, tls: u64, out: &mut Buf) -> Result<()> {
    if c.win {
        c.bytes_call(
            &[
                0x53, 0x48, 0x83, 0xEC, 0x20, 0x48, 0x89, 0xCB, 0xB8, 1, 0, 0, 0, 0x48, 0x85, 0xC9,
                0x48, 0x0F, 0x44, 0xC8, 0x48, 0x85, 0xD2, 0x48, 0x0F, 0x44, 0xD0,
            ],
            "_aligned_malloc",
            out,
        )?;
        let done = x64_jcc(&[0x48, 0x85, 0xC0], 0x74, out);
        c.bytes_call(
            &[0x48, 0x89, 0xC1, 0x31, 0xD2, 0x49, 0x89, 0xD8],
            "memset",
            out,
        )?;
        x64_patch8(done, out);
        out.bytes(&[0x48, 0x83, 0xC4, 0x20, 0x5B, 0xC3]);
        return Ok(());
    }
    if tls != 0 {
        let disp = (tls as i64).wrapping_neg() as i32 as u32;
        let over_align = x64_jcc(&[0x48, 0x83, 0xFE, 0x10], 0x77, out);
        out.bytes(&[0x48, 0x8D, 0x4F, 0xFF, 0x48, 0x81, 0xF9]);
        out.u32(ALLOC_CACHE_MAX_M1);
        let big = x64_fwd(0x77, out);
        out.bytes(&[
            0x48, 0x8D, 0x4F, 0x0F, 0x48, 0x83, 0xE1, 0xF0, 0x64, 0x48, 0x8B, 0x14, 0x25, 0, 0, 0,
            0, 0x48, 0x8D, 0x94, 0x0A,
        ]);
        out.u32(disp);
        let miss = x64_jcc(&[0x48, 0x8B, 0x02, 0x48, 0x85, 0xC0], 0x74, out);
        out.bytes(&[
            0x4C, 0x8B, 0x00, 0x4C, 0x89, 0x02, 0x48, 0xFF, 0x4A, 0x08, 0x48, 0x89, 0xC2, 0x48,
            0x89, 0xC7, 0x48, 0xC1, 0xE9, 0x03, 0x31, 0xC0, 0xF3, 0x48, 0xAB, 0x48, 0x89, 0xD0,
            0xC3,
        ]);
        x64_patch8(miss, out);
        c.bytes_tail(&[0x48, 0x89, 0xCE, 0xBF, 1, 0, 0, 0], "calloc", out)?;
        x64_patch8(big, out);
        c.bytes_tail(
            &[
                0xB8, 1, 0, 0, 0, 0x48, 0x85, 0xFF, 0x48, 0x0F, 0x44, 0xF8, 0x48, 0x89, 0xFE, 0xBF,
                1, 0, 0, 0,
            ],
            "calloc",
            out,
        )?;
        x64_patch8(over_align, out);
        out.bytes(&[0xB8, 1, 0, 0, 0, 0x48, 0x85, 0xFF, 0x48, 0x0F, 0x44, 0xF8]);
    } else {
        c.bytes_tail(
            &[
                0xB8, 1, 0, 0, 0, 0x48, 0x85, 0xFF, 0x48, 0x0F, 0x44, 0xF8, 0x48, 0x83, 0xFE, 0x10,
                0x77, 0x0D, 0x48, 0x89, 0xFE, 0xBF, 1, 0, 0, 0,
            ],
            "calloc",
            out,
        )?;
    }
    c.bytes_call(
        &[
            0x53, 0x48, 0x83, 0xEC, 0x10, 0x48, 0x89, 0xFB, 0x48, 0x89, 0xFA, 0x48, 0xC7, 0x04,
            0x24, 0, 0, 0, 0, 0x48, 0x8D, 0x3C, 0x24,
        ],
        "posix_memalign",
        out,
    )?;
    c.bytes_call(
        &[
            0x85, 0xC0, 0x75, 0x10, 0x48, 0x8B, 0x3C, 0x24, 0x31, 0xF6, 0x48, 0x89, 0xDA,
        ],
        "memset",
        out,
    )?;
    out.bytes(&[0xEB, 0x02, 0x31, 0xC0, 0x48, 0x83, 0xC4, 0x10, 0x5B, 0xC3]);
    Ok(())
}

fn emit_x64_realloc(c: &Emit<'_>, tls: u64, out: &mut Buf) -> Result<()> {
    if c.win {
        return c.bytes_tail(
            &[
                0xB8, 1, 0, 0, 0, 0x4D, 0x85, 0xC9, 0x4C, 0x0F, 0x44, 0xC8, 0x4C, 0x89, 0xCA, 0x4D,
                0x85, 0xC0, 0x4C, 0x0F, 0x44, 0xC0,
            ],
            "_aligned_realloc",
            out,
        );
    }
    if tls != 0 {
        let over_align = x64_jcc(&[0x48, 0x83, 0xFA, 0x10], 0x77, out);
        out.bytes(&[0x4C, 0x8D, 0x41, 0xFF, 0x49, 0x81, 0xF8]);
        out.u32(ALLOC_CACHE_MAX_M1);
        let big_new = x64_fwd(0x77, out);
        out.bytes(&[
            0x48, 0x8D, 0x49, 0x0F, 0x48, 0x83, 0xE1, 0xF0, 0x4C, 0x8D, 0x46, 0xFF, 0x49, 0x81,
            0xF8,
        ]);
        out.u32(ALLOC_CACHE_MAX_M1);
        let big_old = x64_fwd(0x77, out);
        let diff_class = x64_jcc(
            &[
                0x4C, 0x8D, 0x46, 0x0F, 0x49, 0x83, 0xE0, 0xF0, 0x49, 0x39, 0xC8,
            ],
            0x75,
            out,
        );
        out.bytes(&[0x48, 0x89, 0xF8, 0xC3]);
        x64_patch8(big_new, out);
        out.bytes(&[0xB8, 1, 0, 0, 0, 0x48, 0x85, 0xC9, 0x48, 0x0F, 0x44, 0xC8]);
        x64_here(&[big_old, diff_class], out);
        c.bytes_tail(&[0x48, 0x89, 0xCE], "realloc", out)?;
        x64_patch8(over_align, out);
        out.bytes(&[0xB8, 1, 0, 0, 0, 0x48, 0x85, 0xC9, 0x48, 0x0F, 0x44, 0xC8]);
    } else {
        c.bytes_tail(
            &[
                0xB8, 1, 0, 0, 0, 0x48, 0x85, 0xC9, 0x48, 0x0F, 0x44, 0xC8, 0x48, 0x83, 0xFA, 0x10,
                0x77, 0x08, 0x48, 0x89, 0xCE,
            ],
            "realloc",
            out,
        )?;
    }
    c.bytes_call(
        &[
            0x53, 0x41, 0x54, 0x41, 0x55, 0x48, 0x83, 0xEC, 0x10, 0x48, 0x89, 0xFB, 0x49, 0x89,
            0xF4, 0x49, 0x89, 0xCD, 0x48, 0xC7, 0x04, 0x24, 0, 0, 0, 0, 0x48, 0x8D, 0x3C, 0x24,
            0x48, 0x89, 0xD6, 0x48, 0x89, 0xCA,
        ],
        "posix_memalign",
        out,
    )?;
    c.bytes_call(
        &[
            0x85, 0xC0, 0x75, 0x26, 0x48, 0x8B, 0x3C, 0x24, 0x48, 0x89, 0xDE, 0x4C, 0x89, 0xE2,
            0x4D, 0x39, 0xEC, 0x49, 0x0F, 0x47, 0xD5,
        ],
        "memcpy",
        out,
    )?;
    c.bytes_call(&[0x48, 0x89, 0xDF, 0x48, 0x89, 0xC3], "free", out)?;
    out.bytes(&[
        0x48, 0x89, 0xD8, 0xEB, 0x02, 0x31, 0xC0, 0x48, 0x83, 0xC4, 0x10, 0x41, 0x5D, 0x41, 0x5C,
        0x5B, 0xC3,
    ]);
    Ok(())
}

fn emit_x64_fill_once(c: &Emit<'_>, os: Os, out: &mut Buf) -> Result<()> {
    if c.win {
        out.bytes(&[
            0x53, 0x56, 0x57, 0x48, 0x83, 0xEC, 0x20, 0x48, 0x89, 0xCB, 0x48, 0x89, 0xD6, 0x65,
            0x48, 0x8B, 0x3C, 0x25, 0x30, 0x00, 0x00, 0x00,
        ]);
        let retry = out.pos();
        let won = x64_jcc(&[0x31, 0xC0, 0xF0, 0x48, 0x0F, 0xB1, 0x3B], 0x74, out);
        let done_filled = x64_jcc(&[0x48, 0x83, 0xF8, 0x01], 0x74, out);
        let done_reent = x64_jcc(&[0x48, 0x39, 0xF8], 0x74, out);
        c.call("SwitchToThread", out)?;
        out.bytes(&[
            0xEB,
            ((retry as isize - (out.pos() as isize + 2)) as i8) as u8,
        ]);
        x64_patch8(won, out);
        out.bytes(&[0xFF, 0xD6, 0x48, 0xC7, 0x03, 0x01, 0x00, 0x00, 0x00]);
        x64_patch8(done_filled, out);
        x64_patch8(done_reent, out);
        out.bytes(&[0x48, 0x83, 0xC4, 0x20, 0x5F, 0x5E, 0x5B, 0xC3]);
        return Ok(());
    }
    let tp_seg = if os == Os::Darwin { 0x65 } else { 0x64 };
    out.bytes(&[
        0x53, 0x41, 0x54, 0x41, 0x55, 0x48, 0x89, 0xFB, 0x49, 0x89, 0xF4, tp_seg, 0x4C, 0x8B, 0x2C,
        0x25, 0x00, 0x00, 0x00, 0x00,
    ]);
    let retry = out.pos();
    let won = x64_jcc(&[0x31, 0xC0, 0xF0, 0x4C, 0x0F, 0xB1, 0x2B], 0x74, out);
    let done_filled = x64_jcc(&[0x48, 0x83, 0xF8, 0x01], 0x74, out);
    let done_reent = x64_jcc(&[0x4C, 0x39, 0xE8], 0x74, out);
    c.call("sched_yield", out)?;
    out.bytes(&[
        0xEB,
        ((retry as isize - (out.pos() as isize + 2)) as i8) as u8,
    ]);
    x64_patch8(won, out);
    out.bytes(&[0x41, 0xFF, 0xD4, 0x48, 0xC7, 0x03, 0x01, 0x00, 0x00, 0x00]);
    x64_patch8(done_filled, out);
    x64_patch8(done_reent, out);
    out.bytes(&[0x41, 0x5D, 0x41, 0x5C, 0x5B, 0xC3]);
    Ok(())
}

pub(super) fn emit_shim_x64(
    os: Os,
    shim: Shim,
    va: u64,
    addrs: SectionAddrs,
    stub_va: &dyn Fn(&str) -> Result<u64>,
    out: &mut Buf,
) -> Result<()> {
    let c = Emit {
        arch: Arch::X64,
        win: os == Os::Windows,
        va,
        base: out.pos(),
        stub_va,
    };
    match shim {
        Shim::Noop | Shim::Barrier => out.u8(0xC3),
        Shim::Syscall if os == Os::Linux => out.bytes(&[
            0x48, 0x8B, 0x07, 0x48, 0x8B, 0x77, 0x10, 0x48, 0x8B, 0x57, 0x18, 0x4C, 0x8B, 0x57,
            0x20, 0x4C, 0x8B, 0x47, 0x28, 0x4C, 0x8B, 0x4F, 0x30, 0x48, 0x8B, 0x7F, 0x08, 0x0F,
            0x05, 0xC3,
        ]),
        Shim::Syscall => out.bytes(&[0x48, 0xC7, 0xC0, 0xDA, 0xFF, 0xFF, 0xFF, 0xC3]),
        Shim::Cpuid => emit_x64_cpuid(&c, out),
        Shim::ExtendedState => out.bytes(&[
            0x53,
            0xB8,
            1,
            0,
            0,
            0,
            0x0F,
            0xA2,
            0xF7,
            0xC1,
            0,
            0,
            0,
            8,
            0x75,
            4,
            0x31,
            0xC0,
            0x5B,
            0xC3,
            0x89,
            if c.win { 0xC9 } else { 0xF9 },
            0x0F,
            0x01,
            0xD0,
            0x48,
            0xC1,
            0xE2,
            0x20,
            0x48,
            0x09,
            0xD0,
            0x85,
            if c.win { 0xC9 } else { 0xFF },
            0x75,
            2,
            0x24,
            !HIDDEN.xcr0 as u8,
            0x5B,
            0xC3,
        ]),
        Shim::Dealloc => emit_x64_dealloc(&c, addrs.frame_tls, out)?,
        Shim::Alloc => emit_x64_alloc(&c, addrs.frame_tls, out)?,
        Shim::AllocZeroed => emit_x64_alloc_zeroed(&c, addrs.frame_tls, out)?,
        Shim::Realloc => emit_x64_realloc(&c, addrs.frame_tls, out)?,
        Shim::FillOnce => emit_x64_fill_once(&c, os, out)?,
        Shim::ThreadCell if os == Os::Linux => emit_x64_tls_cell(&c, addrs.thread_tls, out)?,
        Shim::ThreadCell => emit_x64_thread_cell(&c, addrs.thread_key, out)?,
        Shim::FrameAlloc | Shim::FrameFree if os == Os::Linux => {
            emit_x64_frame_cache(&c, shim == Shim::FrameAlloc, addrs.frame_tls, out)?
        }
        Shim::FrameAlloc | Shim::FrameFree => c.tail(
            if shim == Shim::FrameAlloc {
                "malloc"
            } else {
                "free"
            },
            out,
        )?,
        Shim::CatchUnwind => unwind::emit_x64_catch_unwind(&c, addrs, out)?,
        Shim::StartPanic => unwind::emit_x64_start_panic(&c, addrs, out)?,
        Shim::StartPanicAbort => c.tail("abort", out)?,
        Shim::PanicCleanup => out.bytes(if c.win {
            &[0x48, 0x8B, 0x01, 0x48, 0x8B, 0x51, 0x08, 0xC3]
        } else {
            &[0x48, 0x8B, 0x07, 0x48, 0x8B, 0x57, 0x08, 0xC3]
        }),
        Shim::DropPush | Shim::DropPop => emit_x64_drop_op(&c, shim == Shim::DropPush, addrs, out)?,
        Shim::UnwindWalk => unwind::emit_walk(Arch::X64, os, out)?,
        Shim::Wide(wide) => wide::emit(Arch::X64, os, wide, out)?,
    }
    Ok(())
}
